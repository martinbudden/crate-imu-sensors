#[derive(Debug, PartialEq)]
pub struct Bmi270<B: ImuBus> {
    pub bus: B,
    pub common: ImuCommon,
    pub config: ImuDeviceConfig,
}

impl<B: ImuBus> ImuDevice for Bmi270<B> {
    type Error = B::Error;

    async fn init(
        &mut self,
        target_output_data_rate_hz: u32,
        gyro_sensitivity: GyroFullScale,
        gyro_units: GyroUnits,
        acc_sensitivity: AccFullScale,
        acc_units: AccUnits,
    ) -> Result<(u32, u32), Self::Error> {
        Bmi270::init(self, target_output_data_rate_hz, gyro_sensitivity, gyro_units, acc_sensitivity, acc_units).await
    }

    async fn read_acc_gyro(&mut self) -> Result<(Vector3f32, Vector3f32), Self::Error> {
        <Self as Imu>::read_acc_gyro(self).await
    }
}

impl<B: ImuBus> Imu for Bmi270<B> {
    type Bus = B;
    type Error = <B as ImuBus>::Error;

    #[inline]
    fn bus(&mut self) -> &mut Self::Bus {
        &mut self.bus
    }

    #[inline]
    fn common(&self) -> &ImuCommon {
        &self.common
    }

    #[inline]
    fn common_mut(&mut self) -> &mut ImuCommon {
        &mut self.common
    }

    #[inline]
    fn config(&self) -> &ImuDeviceConfig {
        &self.config
    }

    async fn read_acc(&mut self) -> Result<Vector3f32, Self::Error> {
        let mut buf = [0u8; 6];
        self.write_read(&[REG_ACC_X_L], &mut buf).await?;
        let acc = Vector3f32::from_le_bytes_6(buf) * self.common.acc_scale - self.common.acc_offset;
        Ok(ImuAxisOrder::map_vector(self.common.axis_order, acc))
    }

    async fn read_gyro(&mut self) -> Result<Vector3f32, Self::Error> {
        let mut buf = [0u8; 6];
        self.write_read(&[REG_GYRO_X_L], &mut buf).await?;
        let gyro = Vector3f32::from_le_bytes_6(buf) * self.common.gyro_scale - self.common.gyro_offset;
        Ok(ImuAxisOrder::map_vector(self.common.axis_order, gyro))
    }

    async fn read_acc_gyro(&mut self) -> Result<(Vector3f32, Vector3f32), Self::Error> {
        let mut buf = [0u8; 12];
        self.write_read(&[REG_ACC_X_L], &mut buf).await?;

        let [a0, a1, a2, a3, a4, a5, g0, g1, g2, g3, g4, g5] = buf;

        let acc_buf = [a0, a1, a2, a3, a4, a5];
        let gyro_buf = [g0, g1, g2, g3, g4, g5];
        let acc = Vector3f32::from_le_bytes_6(acc_buf) * self.common.acc_scale - self.common.acc_offset;
        let gyro = Vector3f32::from_le_bytes_6(gyro_buf) * self.common.gyro_scale - self.common.gyro_offset;
        Ok(ImuAxisOrder::map_acc_gyro(self.common.axis_order, acc, gyro))
    }
}

async fn delay_ms(delay: u32) {
    Timer::after(Duration::from_millis(delay.into())).await;
}

impl<B: ImuBus> Bmi270<B> {
    const DEVICE_ID: u8 = 0x68;

    /// Constructor.
    pub fn new(bus: B, axis_order: ImuAxisOrder) -> Self {
        Self {
            bus,
            common: ImuCommon::new(axis_order),
            config: ImuDeviceConfig {
                gyro_id_msp: ImuDeviceConfig::MSP_GYRO_ID_LSM6DSO,
                acc_id_msp: ImuDeviceConfig::MSP_ACC_ID_LSM6DSO,
                axis_order,
                device_id: Self::DEVICE_ID,
                address: I2C_ADDRESS,
                flags: 0,
            },
        }
    }

    /// # Errors
    pub async fn write_register(&mut self, reg: u8, data: u8) -> Result<(), B::Error> {
        self.bus.write_register(self.config.address, reg, data).await
    }

    /// # Errors
    pub async fn init(
        &mut self,
        target_output_data_rate_hz: u32,
        gyro_sensitivity: GyroFullScale,
        gyro_units: GyroUnits,
        acc_sensitivity: AccFullScale,
        acc_units: AccUnits,
    ) -> Result<(u32, u32), B::Error> {
        const DATA_READY_INI_1: u8 = 0b_0000_0100;
        const DATA_READY_INI_2: u8 = 0b_0100_0000;
        const ACTIVE_HIGH: u8 = 0b_0000_0010; // active high and active low are the only options
        const OUTPUT_ENABLE: u8 = 0b_0000_0100;

        // Software reset
        self.write_register(REG_CMD, 0xB6).await?; // Soft reset
        delay_ms(1).await;

        delay_ms(100).await;
        // Power save disabled
        self.write_register(REG_PWR_CONF, 0x00).await?;
        // 450us is minimum delay required
        delay_ms(1).await;

        // prepare config load
        self.write_register(REG_INIT_CTRL, 0x00).await?;
        delay_ms(1).await;

        // Write 8kB initialization data to Register INIT_DATA. This requires 6.6ms at 10 MHz SPI I/F frequency.
        _ = self.load_configuration_data().await?;

        // enable gyro, acc and temp sensors
        self.write_register(REG_PWR_CTRL, 0x0E).await?;
        delay_ms(1).await;

        // disable advanced power save, enable FIFO self-wake - power mode
        self.write_register(REG_PWR_CONF, 0x02).await?;
        delay_ms(1).await;

        // all FIFOs disabled
        self.write_register(REG_FIFO_CONFIG_1, 0x00).await?;
        delay_ms(1).await;

        // configure interrupts
        // enable the data ready interrupt pins 1 and 2
        self.write_register(REG_INT_MAP_DATA, DATA_READY_INI_1 | DATA_READY_INI_2).await?;
        delay_ms(1).await;
        // input disabled, push-pull are defaults
        self.write_register(REG_INT1_IO_CTRL, OUTPUT_ENABLE | ACTIVE_HIGH).await?;
        delay_ms(1).await;
        // input disabled, push-pull are defaults
        self.write_register(REG_INT2_IO_CTRL, OUTPUT_ENABLE | ACTIVE_HIGH).await?;
        delay_ms(1).await;
        // interrupt latching off
        self.write_register(REG_INT_LATCH, 0).await?;
        delay_ms(1).await;

        let gyro_register_value =
            self.calculate_gyro_scale_and_odr(gyro_sensitivity, gyro_units, target_output_data_rate_hz);
        self.write_register(REG_GYR_CONF, gyro_register_value).await?;

        let acc_register_value =
            self.calculate_acc_scale_and_odr(acc_sensitivity, acc_units, target_output_data_rate_hz);
        self.write_register(REG_ACC_CONF, acc_register_value).await?;

        // return the gyro and acc sample rates actually set
        Ok((self.common.gyro_sample_rate_hz, self.common.acc_sample_rate_hz))
    }

    pub fn calculate_gyro_scale_and_odr(
        &mut self,
        gyro_sensitivity: GyroFullScale,
        gyro_units: GyroUnits,
        target_output_data_rate_hz: u32,
    ) -> u8 {
        const GYRO_RANGE_125_DPS: u8 = 0x04;
        const GYRO_RANGE_250_DPS: u8 = 0x03;
        const GYRO_RANGE_500_DPS: u8 = 0x02;
        const GYRO_RANGE_1000_DPS: u8 = 0x01;
        const GYRO_RANGE_2000_DPS: u8 = 0x00;
        const GYRO_FILTER_PERFORMANCE_OPTIMIZED: u8 = 0b_1100_0000; // ie not power optimized
        const GYRO_ODR_25_HZ: u8 = 0x06;
        const GYRO_ODR_50_HZ: u8 = 0x07;
        const GYRO_ODR_100_HZ: u8 = 0x08;
        const GYRO_ODR_200_HZ: u8 = 0x09;
        const GYRO_ODR_400_HZ: u8 = 0x0A;
        const GYRO_ODR_800_HZ: u8 = 0x0B;
        const GYRO_ODR_1600_HZ: u8 = 0x0C;
        const GYRO_ODR_3200_HZ: u8 = 0x0D; // for gyro only, acc does not support this rate

        let (scale_dps, gyro_register_value) = match gyro_sensitivity {
            GyroFullScale::Scale125Dps => (125.0 / 32768.0, GYRO_RANGE_125_DPS),
            GyroFullScale::Scale250Dps => (250.0 / 32768.0, GYRO_RANGE_250_DPS),
            GyroFullScale::Scale500Dps => (500.0 / 32768.0, GYRO_RANGE_500_DPS),
            GyroFullScale::Scale1000Dps => (1000.0 / 32768.0, GYRO_RANGE_1000_DPS),
            _ => (2000.0 / 32768.0, GYRO_RANGE_2000_DPS),
        };
        self.common.gyro_scale = if gyro_units == GyroUnits::Dps { scale_dps } else { scale_dps.to_radians() };

        let (gyro_sample_rate_hz, gyro_odr) = match target_output_data_rate_hz {
            801..=1600 => (1600, GYRO_ODR_1600_HZ),
            401..=800 => (800, GYRO_ODR_800_HZ),
            201..=400 => (400, GYRO_ODR_400_HZ),
            101..=200 => (200, GYRO_ODR_200_HZ),
            51..=100 => (100, GYRO_ODR_100_HZ),
            26..=50 => (50, GYRO_ODR_50_HZ),
            1..=25 => (25, GYRO_ODR_25_HZ),
            _ => (3200, GYRO_ODR_3200_HZ),
        };
        self.common.gyro_sample_rate_hz = gyro_sample_rate_hz;

        gyro_register_value | gyro_odr | GYRO_FILTER_PERFORMANCE_OPTIMIZED
    }

    pub fn calculate_acc_scale_and_odr(
        &mut self,
        acc_sensitivity: AccFullScale,
        acc_units: AccUnits,
        target_output_data_rate_hz: u32,
    ) -> u8 {
        const ACC_FILTER_PERFORMANCE_OPTIMIZED: u8 = 0b_1000_0000; // ie not power optimized
        const ACC_ODR_25_HZ: u8 = 0x06;
        const ACC_ODR_50_HZ: u8 = 0x07;
        const ACC_ODR_100_HZ: u8 = 0x08;
        const ACC_ODR_200_HZ: u8 = 0x09;
        const ACC_ODR_400_HZ: u8 = 0x0A;
        const ACC_ODR_800_HZ: u8 = 0x0B;
        const ACC_ODR_1600_HZ: u8 = 0x0C;
        const ACC_RANGE_2G: u8 = 0x00;
        const ACC_RANGE_4G: u8 = 0x01;
        const ACC_RANGE_8G: u8 = 0x02;
        const ACC_RANGE_16G: u8 = 0x03;

        let (scale, acc_register_value) = match acc_sensitivity {
            AccFullScale::Scale2G => (2.0 / 32768.0, ACC_RANGE_2G),
            AccFullScale::Scale4G => (4.0 / 32768.0, ACC_RANGE_4G),
            AccFullScale::Scale8G => (8.0 / 32768.0, ACC_RANGE_8G),
            _ => {
                // default includes  AccFullScale::Scale16G
                (16.0 / 32768.0, ACC_RANGE_16G)
            }
        };
        self.common.acc_scale = if acc_units == AccUnits::G { scale } else { scale * ImuCommon::G0 };

        let (acc_sample_rate_hz, acc_odr) = match target_output_data_rate_hz {
            401..=800 => (800, ACC_ODR_800_HZ),
            201..=400 => (400, ACC_ODR_400_HZ),
            101..=200 => (200, ACC_ODR_200_HZ),
            51..=100 => (100, ACC_ODR_100_HZ),
            26..=50 => (50, ACC_ODR_50_HZ),
            1..=25 => (25, ACC_ODR_25_HZ),
            _ => (1600, ACC_ODR_1600_HZ),
        };
        self.common.acc_sample_rate_hz = acc_sample_rate_hz;

        acc_register_value | acc_odr | ACC_FILTER_PERFORMANCE_OPTIMIZED
    }

    async fn load_configuration_data(&mut self) -> Result<u8, B::Error> {
        const DATA_SIZE: usize = IMU_BMI270_CONFIG_DATA.len();
        #[allow(clippy::cast_possible_truncation)]
        const ADDRESS_ARRAY: [u8; 2] = [((DATA_SIZE >> 1) & 0x0F) as u8, (DATA_SIZE >> 5) as u8];
        const BUS_WRITE_CHUNK_SIZE: usize = 32;
        self.bus.write_registers(self.config.address, REG_INIT_ADDR_0, &ADDRESS_ARRAY).await?;

        for ii in (0..DATA_SIZE).step_by(BUS_WRITE_CHUNK_SIZE) {
            let chunk = &IMU_BMI270_CONFIG_DATA[ii..ii + BUS_WRITE_CHUNK_SIZE];
            self.bus.write_registers(self.config.address, REG_INIT_DATA, chunk).await?;
        }

        // complete config load
        self.write_register(REG_INIT_CTRL, 0x01).await?;
        delay_ms(10).await;
        let internal_status = self.bus.read_register(self.config.address, REG_INTERNAL_STATUS).await?;
        //assert(internal_status == INIT_OK || internal_status == SENSOR_STOPPED);
        Ok(internal_status)
    }
}

